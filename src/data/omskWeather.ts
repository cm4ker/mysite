/** Наклон МНК по точкам (x, y); возвращает изменение за десятилетие и функцию линии. */
export function ols(points: Array<[number, number]>) {
  const n = points.length;
  const mx = points.reduce((s, p) => s + p[0], 0) / n;
  const my = points.reduce((s, p) => s + p[1], 0) / n;
  let num = 0;
  let den = 0;
  for (const [x, y] of points) {
    num += (x - mx) * (y - my);
    den += (x - mx) ** 2;
  }
  const slope = den === 0 ? 0 : num / den;
  return {
    perDecade: slope * 10,
    at: (x: number) => my + slope * (x - mx),
  };
}

/** Скользящее среднее по окну; null там, где окно неполное. */
export function movingAverage(values: Array<number | null>, window: number): Array<number | null> {
  const half = Math.floor(window / 2);
  return values.map((_, i) => {
    const from = i - half;
    const to = i + half;
    if (from < 0 || to >= values.length) return null;
    const slice = values.slice(from, to + 1).filter((v): v is number => v !== null);
    if (slice.length < window - 2) return null;
    return slice.reduce((s, v) => s + v, 0) / slice.length;
  });
}
